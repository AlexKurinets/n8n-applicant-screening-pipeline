#!/usr/bin/env node
// Keeps the n8n Code nodes in workflows/*.json in step with src/code-nodes.
//
// Every Code node starts with a header line naming its source module, e.g.
//   // source: src/code-nodes/boolean-prefilter.js {"strict": true}
// This script bundles that module and the src/lib modules it requires into the
// node's jsCode, so the code the unit tests exercise is the code n8n runs.
//
//   node scripts/sync-code-nodes.mjs          rewrite the workflow files
//   node scripts/sync-code-nodes.mjs --check  fail if any node is out of date (CI)

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER = /^\/\/ source: (src\/code-nodes\/[\w.-]+\.js)(?: (\{.*\}))?$/;

function collect(entry, defs = new Map()) {
  if (defs.has(entry)) return defs;
  const source = readFileSync(join(root, entry), 'utf8');
  const deps = {};
  defs.set(entry, { source, deps });
  for (const m of source.matchAll(/require\('(\.{1,2}\/[^']+)'\)/g)) {
    const target = posix.normalize(posix.join(posix.dirname(entry), m[1])).replace(/(\.js)?$/, '.js');
    deps[m[1]] = target;
    collect(target, defs);
  }
  return defs;
}

export function bundle(entry, options, nodeName) {
  const defs = collect(entry);
  const lines = [
    `// source: ${entry}${options ? ` ${options}` : ''}`,
    '// Generated by scripts/sync-code-nodes.mjs. Edit the source file and re-run the script, not this node.',
    'const __defs = {',
  ];
  for (const [key, { source, deps }] of defs) {
    lines.push(`${JSON.stringify(key)}: [function (module, exports, require) {`, source.trimEnd(), `}, ${JSON.stringify(deps)}],`);
  }
  lines.push(
    '};',
    'const __cache = {};',
    'function __load(key) {',
    '  if (__cache[key]) return __cache[key].exports;',
    '  const [fn, deps] = __defs[key];',
    '  const module = { exports: {} };',
    '  __cache[key] = module;',
    "  fn(module, module.exports, (p) => { if (!(p in deps)) throw new Error('not bundled: ' + p); return __load(deps[p]); });",
    '  return module.exports;',
    '}',
    'const __ctx = {',
    '  node: (name) => $(name).first().json,',
    '  executed: (name) => $(name).isExecuted,',
    '  executionId: $execution.id,',
    "  prevNode: typeof $prevNode !== 'undefined' && $prevNode ? $prevNode.name : null,",
    '};',
    '// Errors name this node, so a dead letter says where the run stopped.',
    'try {',
    `  return __load(${JSON.stringify(entry)}).run($input.all(), __ctx, ${options || '{}'});`,
    '} catch (e) {',
    `  if (e && typeof e.message === 'string' && !e.message.includes('(node: ')) e.message = e.message.replace(/^(\\[[A-Z_]+\\] )?/, (m) => m + ${JSON.stringify(`(node: ${nodeName}) `)});`,
    '  throw e;',
    '}',
  );
  return lines.join('\n');
}

function syncFile(file, check) {
  const wf = JSON.parse(readFileSync(file, 'utf8'));
  const stale = [];
  for (const node of wf.nodes) {
    if (node.type !== 'n8n-nodes-base.code') continue;
    const first = String(node.parameters.jsCode || '').split('\n', 1)[0];
    const m = first.match(HEADER);
    if (!m) throw new Error(`${relative(root, file)}: Code node "${node.name}" has no "// source:" header`);
    const code = bundle(m[1], m[2], node.name);
    if (code !== node.parameters.jsCode) {
      stale.push(node.name);
      node.parameters.jsCode = code;
    }
  }
  if (stale.length && !check) writeFileSync(file, `${JSON.stringify(wf, null, 2)}\n`);
  return stale;
}

function main() {
  const check = process.argv.includes('--check');
  const dir = join(root, 'workflows');
  let drift = 0;
  for (const name of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const stale = syncFile(join(dir, name), check);
    if (stale.length) {
      drift += stale.length;
      console.log(`${check ? 'out of date' : 'updated'}: workflows/${name}: ${stale.join(', ')}`);
    }
  }
  if (check && drift) {
    console.error(`${drift} Code node(s) differ from src/code-nodes. Run: node scripts/sync-code-nodes.mjs`);
    process.exit(1);
  }
  console.log(check ? 'Code nodes match src/code-nodes.' : `Synced (${drift} node(s) changed).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
